"""Evaluate explicit annotations, retaining prediction abstentions as errors.

No gold labels are inferred from ratings or generated by this tool.
"""
import argparse
import csv
import hashlib
import json
from collections import Counter, defaultdict
from pathlib import Path

LABELS = ("positive", "negative", "neutral", "mixed", "unscored")


def metrics(pairs):
    confusion = Counter(pairs)
    classes = {}
    for label in LABELS:
        tp = confusion[label, label]
        support = sum(count for (gold, _), count in confusion.items() if gold == label)
        predicted = sum(count for (_, pred), count in confusion.items() if pred == label)
        precision = tp / predicted if predicted else 0.0
        recall = tp / support if support else 0.0
        f1 = 2 * tp / (support + predicted) if support + predicted else 0.0
        classes[label] = {"support": support, "predicted": predicted, "precision": precision,
                          "recall": recall, "f1": f1}
    supported = [value["f1"] for value in classes.values() if value["support"]]
    return {"labeled_aspects": len(pairs), "accuracy": sum(g == p for g, p in pairs) / len(pairs),
            "macro_f1_supported_labels": sum(supported) / len(supported),
            "abstentions_on_opinions": sum(g != "unscored" and p == "unscored" for g, p in pairs),
            "classes": classes, "confusion": [{"gold": g, "predicted": p, "count": n}
                                               for (g, p), n in sorted(confusion.items())]}


def evaluate(predictions, annotations, kind, split="holdout"):
    lookup = {}
    for line in Path(predictions).open(encoding="utf-8"):
        record = json.loads(line)
        identity = (record["source"], record["cafe_id"], record["review_id"])
        if identity in lookup:
            raise ValueError("Duplicate prediction identity")
        lookup[identity] = record
    seen, pairs, by_category = set(), [], defaultdict(list)
    blank, eligible = 0, 0
    for row in csv.DictReader(Path(annotations).open(encoding="utf-8-sig", newline="")):
        if split != "all" and row.get("split") != split:
            continue
        eligible += 1
        gold = row.get("gold_label", "").strip()
        if not gold:
            blank += 1
            continue
        if gold not in LABELS or not row.get("reviewer", "").strip():
            raise ValueError("Each labeled row needs a valid gold_label and reviewer")
        identity = (row["source"], row["cafe_id"], row["review_id"])
        aspect = (*identity, row["category"])
        if aspect in seen:
            raise ValueError("Duplicate labeled aspect")
        seen.add(aspect)
        record = lookup.get(identity)
        if record is None or row["category"] not in record["categories"]:
            raise ValueError("Annotation has no matching prediction")
        if row.get("text") and row["text"] != record["original_text"]:
            raise ValueError("Annotation text differs from prediction input")
        pair = (gold, record["categories"][row["category"]]["label"])
        pairs.append(pair)
        by_category[row["category"]].append(pair)
    if not pairs:
        raise ValueError("No labeled aspects; accuracy cannot be calculated")
    return {"annotation_kind": kind, "split": split, "eligible_annotation_rows": eligible,
            "unlabeled_rows": blank, "annotation_completion": len(pairs) / eligible,
            "interpretation": "Human-label comparison" if kind == "human" else
                "Synthetic/provisional comparison; not human-validated real-review accuracy",
            "predictions_sha256": hashlib.sha256(Path(predictions).read_bytes()).hexdigest(),
            "annotations_sha256": hashlib.sha256(Path(annotations).read_bytes()).hexdigest(),
            "overall": metrics(pairs),
            "categories": {key: metrics(value) for key, value in sorted(by_category.items())}}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--predictions", required=True)
    parser.add_argument("--annotations", required=True)
    parser.add_argument("--kind", choices=("human", "codex_provisional", "synthetic"), required=True)
    parser.add_argument("--split", default="holdout")
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    output = Path(args.output)
    if output.exists():
        parser.error("Output exists; choose a new file")
    try:
        report = evaluate(args.predictions, args.annotations, args.kind, args.split)
    except (ValueError, KeyError, OSError) as error:
        parser.error(str(error))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"output": str(output), "labeled_aspects": report["overall"]["labeled_aspects"]}))


if __name__ == "__main__":
    main()

const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const core=vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../src/cafe_sentiment/resources/annotation-core.js'),'utf8')+';AnnotationCore');
const review={key:'["synthetic","a","1"]',source:'synthetic',cafe_id:'a',review_id:'1',split:'holdout',text:'🐻 커피는 맛있어요. 케이크는 맛없어요.',text_sha256:'text-hash',categories:['menu','service']};
const data={dataset_sha256:'dataset-1',reviews:[review],categories:{menu:'메뉴',service:'친절'}};
const decisions={};
assert.equal(core.counts(data.reviews,decisions).pending,2);
decisions[core.key(review,'menu')]={label:'positive',evidence:'',notes:''};
assert.equal(core.validate(review,decisions[core.key(review,'menu')]).status,'invalid');
decisions[core.key(review,'menu')].evidence='없는 표현';assert.equal(core.validate(review,decisions[core.key(review,'menu')]).status,'invalid');
decisions[core.key(review,'menu')]={label:'mixed',evidence:'맛있어요\n맛없어요',notes:'좋음과 나쁨이 함께 있음'};
assert.equal(core.validate(review,decisions[core.key(review,'menu')]).status,'labeled');
decisions[core.key(review,'service')]={label:'deferred',evidence:'',notes:''};
assert.equal(core.validate(review,decisions[core.key(review,'service')]).status,'invalid');
decisions[core.key(review,'service')].notes='대상이 모호함';
assert.equal(core.counts(data.reviews,decisions).deferred,1);assert.equal(core.counts(data.reviews,decisions).finished_reviews,1);
const saved=core.snapshot(data,'검토자 A',decisions,review.key),restored=core.parseSnapshot(data,JSON.stringify(saved));
assert.equal(restored.reviewer,'검토자 A');assert.equal(core.counts(data.reviews,restored.decisions).labeled,1);
assert.throws(()=>core.parseSnapshot(data,{...saved,dataset_sha256:'other'}));
assert.throws(()=>core.parseSnapshot(data,{...saved,decisions:[...saved.decisions,saved.decisions[0]]}));
assert.throws(()=>core.parseSnapshot(data,{...saved,decisions:[{...saved.decisions[0],category:'wrong'}]}));
const csv=core.csv(data,'검토자 A',restored.decisions);
assert.ok(csv.startsWith('\uFEFF'));assert.ok(csv.includes('"mixed"'));assert.ok(csv.includes('[판단 보류] 대상이 모호함'));
assert.ok(csv.includes('input_text_sha256'));assert.ok(!csv.includes(review.text));
assert.throws(()=>core.csv(data,'',restored.decisions));
const independent={};assert.equal(core.counts(data.reviews,independent).labeled,0);
console.log('Annotation checks passed: evidence, mixed, defer, snapshot round-trip, dataset binding, CSV and independent drafts');
